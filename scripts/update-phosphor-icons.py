cache=Path('/tmp/phosphor-selection');cache.mkdir(exist_ok=True)
unique=sorted(set(mapping.values()))
def fetch(n):
 name,_,weight=n.partition(':');weight=weight or 'bold'
 url=base+f'assets/{weight}/{name}-{weight}.svg'
 try:
  content=urllib.request.urlopen(url).read().decode();ET.fromstring(content)
  (cache/(n.replace(':','-')+'.svg')).write_text(content)
  return n,content
 except Exception as e:return n,None
results=dict(concurrent.futures.ThreadPoolExecutor(12).map(fetch,unique))
missing=[n for n,s in results.items() if s is None];print('Missing:',missing)
